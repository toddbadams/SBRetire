"""F-021.3 — Claude Design hand-off: docs/design/sample (example-config runs only) and the design prompt.

The sample is generated by scripts/build_design_sample.py from config/model.example.yaml and committed; these
tests only read it.
"""

from __future__ import annotations

import dataclasses
import json
import re
from pathlib import Path
from typing import Any

import jsonschema

from sbretire.config import Scenario, load_scenario
from sbretire.inputs_report import scenario_input_rows
from sbretire.randomness import ResolvedSeed
from sbretire.results_json import RUNS_JS_PREFIX

ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / "docs" / "design"
SAMPLE = DESIGN / "sample" / "runs"
SCHEMA = json.loads((ROOT / "schemas" / "results.schema.json").read_text(encoding="utf-8"))


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _example_with(results: dict[str, Any]) -> Scenario:
    """config/model.example.yaml with the run's headline overrides (return and the two budget options)."""
    example = load_scenario(ROOT / "config" / "model.example.yaml").scenario
    run = results["run"]
    budget = example.budget.model_copy(update=run["options"])
    portfolio = example.portfolio.model_copy(update={"annual_return": run["annual_return"]})
    return example.model_copy(update={"budget": budget, "portfolio": portfolio})


def test_design_sample_is_valid_example_data() -> None:
    folders = sorted(path for path in SAMPLE.iterdir() if path.is_dir())
    assert len(folders) == 2
    runs = {}
    for folder in folders:
        results = _load(folder / "results.json")
        jsonschema.validate(results, SCHEMA)
        assert results["run"]["name"] == folder.name and results["run"]["config_file"] == "model.example.yaml"
        expected_rows = scenario_input_rows(_example_with(results), ResolvedSeed(42, "config"))
        assert results["inputs"] == [dataclasses.asdict(row) for row in expected_rows], folder.name
        runs[folder.name] = results
    assert any(results["run"]["options"]["end_reserve_months"] > 0 for results in runs.values())
    index = _load(SAMPLE / "index.json")
    assert {entry["name"] for entry in index["runs"]} == set(runs)
    text = (SAMPLE / "runs.js").read_text(encoding="utf-8")
    assert text.startswith(RUNS_JS_PREFIX) and text.endswith(";\n")
    payload = json.loads(text[len(RUNS_JS_PREFIX) : -2])
    assert payload == {"schema_version": "1.0", "index": index["runs"], "runs": runs}


def test_design_prompt_covers_schema_sections() -> None:
    prompt = (DESIGN / "claude-design-prompt.md").read_text(encoding="utf-8")
    for section in SCHEMA["properties"]:
        assert f"`{section}`" in prompt, section
    required_parts = (
        "run picker",
        "compare",
        "headline",
        "maximum sustainable budget",
        "reserve",
        "required return",
        "fan chart",
        "survival",
        "inputs",
        "column",
        "not a confidence interval",
        "file://",
        "offline",
        "dark",
        "window.SBRETIRE_RUNS",
        "runs/runs.js",
    )
    lowered = prompt.lower()
    missing = [part for part in required_parts if part.lower() not in lowered]
    assert missing == []
    assert re.search(r"sample/runs/runs\.js", prompt)
